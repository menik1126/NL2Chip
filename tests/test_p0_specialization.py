def _width_plan(
    widths: tuple[int, ...] = (3, 5),
    *,
    design_name: str = "p0_xor",
    parameter_name: str = "WIDTH",
) -> FiniteParameterPlan:
    return FiniteParameterPlan(
        design_name=design_name,
        parameter_names=(parameter_name,),
        cases=tuple(
            SpecializationCase(
                ((parameter_name, width),),
                f"{design_name}__p0__{parameter_name}_{width}",
            )
            for width in widths
        ),
    )


