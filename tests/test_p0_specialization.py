def test_derived_width_is_body_localparam_and_matches_concrete_cores():
    plan = _width_plan(
        (3, 5),
        design_name="Bit_Difference_Counter",
        parameter_name="BIT_WIDTH",
    )
    modules = {}
    for case, count_width in zip(plan.cases, (2, 3)):
        bit_width = case.values["BIT_WIDTH"]
        modules[case.module_name] = f"""
        module {case.module_name} (
            input logic [{bit_width - 1}:0] _gen_input_A,
            input logic [{bit_width - 1}:0] _gen_input_B,
            output logic [{count_width - 1}:0] count
        );
            assign count = '0;
        endmodule
        """

    code, manifest = generate_cvdp_specialization_wrapper(
        design_name=plan.design_name,
        plan=plan,
        modules=modules,
        expected_ports=[
            ("input", "logic [BIT_WIDTH-1:0]", "input_A"),
            ("input", "logic [BIT_WIDTH-1:0]", "input_B"),
            ("output", "logic [COUNT_WIDTH-1:0]", "count"),
        ],
        ref_code="",
        harness_files={
            "src/test.py": (
                "runner.build(parameters={'BIT_WIDTH': BIT_WIDTH})\n"
                "dut.input_A.value = 0\ndut.input_B.value = 0\n"
                "int(dut.count.value)\nint(dut.COUNT_WIDTH.value)"
            )
        },
        derived_parameter_names={"COUNT_WIDTH"},
    )

    assert code is not None, manifest
    parameter_header = code.split(")\n (", 1)[0]
    assert "parameter integer BIT_WIDTH" in parameter_header
    assert "parameter integer COUNT_WIDTH" not in parameter_header
    assert "localparam integer COUNT_WIDTH" in code
    assert manifest["derived_parameter_values"] == {"COUNT_WIDTH": [2, 3]}


