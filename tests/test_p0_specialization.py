def _xor_modules(plan: FiniteParameterPlan) -> dict[str, str]:
    modules = {}
    for case in plan.cases:
        width = next(iter(case.values.values()))
        modules[case.module_name] = f"""
        // Generated by Sparkle HDL
        module {case.module_name} (
            input logic [{width - 1}:0] _gen_lhs,
            input logic [{width - 1}:0] _gen_rhs,
            output logic [{width - 1}:0] out
        );
            assign out = _gen_lhs ^ _gen_rhs;
        endmodule
        """
    return modules


def _generate_xor_wrapper(
    plan: FiniteParameterPlan,
    modules: dict[str, str] | None = None,
):
    return generate_cvdp_specialization_wrapper(
        design_name=plan.design_name,
        plan=plan,
        modules=modules if modules is not None else _xor_modules(plan),
        expected_ports=[
            ("input", "logic [WIDTH-1:0]", "lhs"),
            ("input", "logic [WIDTH-1:0]", "rhs"),
            ("output", "logic [WIDTH-1:0]", "out"),
        ],
        ref_code="",
        harness_files={
            "src/test_runner.py": (
                "runner.build(parameters={'WIDTH': WIDTH})\n"
                "dut.lhs.value = 0\ndut.rhs.value = 0\nint(dut.out.value)"
            )
        },
    )


def test_real_cvdp_p0_family_is_12_tasks_and_60_specializations():
    dataset = Dataset("cvdp", PROJECT_ROOT)
    try:
        dataset.discover_problems(limit=1)
    except FileNotFoundError as exc:
        pytest.skip(str(exc))

    plans = {}
    for prob_id, expected_count in P0_PARAMETER_TASKS.items():
        info = dataset.load_problem(prob_id)
        plan = discover_finite_parameter_plan(
            design_name=info.design_name,
            harness_files=info.metadata["harness_files"],
        )
        assert plan.supported, (prob_id, plan.diagnostics)
        assert len(plan.cases) == expected_count, prob_id
        plans[prob_id] = plan

    assert sum(len(plan.cases) for plan in plans.values()) == 60

    assert [
        case.values for case in plans["cvdp_copilot_filo_0005"].cases
    ] == [
        {"DATA_WIDTH": 8, "FILO_DEPTH": 8},
        {"DATA_WIDTH": 10, "FILO_DEPTH": 12},
        {"DATA_WIDTH": 10, "FILO_DEPTH": 16},
        {"DATA_WIDTH": 12, "FILO_DEPTH": 12},
        {"DATA_WIDTH": 12, "FILO_DEPTH": 16},
    ]

    expected_hamming = [
        {"DATA_WIDTH": 4, "PARITY_BIT": 3},
        {"DATA_WIDTH": 8, "PARITY_BIT": 4},
        {"DATA_WIDTH": 16, "PARITY_BIT": 5},
        {"DATA_WIDTH": 32, "PARITY_BIT": 6},
        {"DATA_WIDTH": 64, "PARITY_BIT": 7},
        {"DATA_WIDTH": 128, "PARITY_BIT": 8},
    ]
    for prob_id in (
        "cvdp_copilot_hamming_code_tx_and_rx_0009",
        "cvdp_copilot_hamming_code_tx_and_rx_0011",
    ):
        assert [case.values for case in plans[prob_id].cases] == expected_hamming

    assert [
        case.values for case in plans["cvdp_copilot_sync_lifo_0001"].cases
    ] == [
        {"ADDR_WIDTH": 2, "DATA_WIDTH": 4},
        {"ADDR_WIDTH": 3, "DATA_WIDTH": 8},
        {"ADDR_WIDTH": 4, "DATA_WIDTH": 16},
        {"ADDR_WIDTH": 6, "DATA_WIDTH": 64},
        {"ADDR_WIDTH": 7, "DATA_WIDTH": 128},
    ]


def test_dice_contract_recovers_symbolic_output_and_derived_width():
    dataset = Dataset("cvdp", PROJECT_ROOT)
    try:
        info = dataset.load_problem("cvdp_copilot_digital_dice_roller_0004")
    except FileNotFoundError as exc:
        pytest.skip(str(exc))
    plan = discover_finite_parameter_plan(
        design_name=info.design_name,
        harness_files=info.metadata["harness_files"],
    )
    payload = plan.to_dict()
    info.metadata["finite_parameter_plan"] = payload

    ports = _p0_benchmark_expected_ports(info)
    prompt_parameters = _p0_parse_parameters_from_prompt(info.prompt_text)
    public_types = "\n".join(typ for _, typ, _ in ports)
    derived = {
        name
        for name in prompt_parameters - set(plan.parameter_names)
        if re.search(rf"\b{re.escape(name)}\b", public_types)
    }

    assert (
        "output",
        "logic [(NUM_DICE * BIT_WIDTH) - 1:0]",
        "dice_values",
    ) in ports
    assert derived == {"BIT_WIDTH"}


