def _plan(widths: tuple[int, ...] = (3, 17, 65)) -> FiniteParameterPlan:
    return FiniteParameterPlan(
        design_name="native_xor",
        parameter_names=("WIDTH",),
        cases=tuple(
            SpecializationCase(
                parameters=(("WIDTH", width),),
                module_name=f"unused_{width}",
            )
            for width in widths
        ),
    )


GENERIC_XOR = """
// Generated by Sparkle HDL
module native_xor #(
    parameter integer WIDTH = 8
) (
    input logic [WIDTH-1:0] _gen_lhs,
    input logic [WIDTH-1:0] _gen_rhs,
    output logic [WIDTH-1:0] out
);
    assign out = _gen_lhs ^ _gen_rhs;
endmodule
"""


REF_XOR = """
module native_xor #(
    parameter WIDTH = 8
) (
    input logic [WIDTH-1:0] lhs,
    input logic [WIDTH-1:0] rhs,
    output logic [WIDTH-1:0] out
);
endmodule
"""


HARNESS = {
    "src/test_runner.py": """
        runner.build(parameters={"WIDTH": WIDTH})
        dut.lhs.value = 0
        dut.rhs.value = 0
        assert int(dut.out.value) == 0
    """,
}


EXPECTED_PORTS = [
    ("input", "logic [WIDTH-1:0]", "lhs"),
    ("input", "logic [WIDTH-1:0]", "rhs"),
    ("output", "logic [WIDTH-1:0]", "out"),
]


def _prepare(sv_code: str = GENERIC_XOR):
    return prepare_cvdp_native_parameter_design(
        sv_code=sv_code,
        design_name="native_xor",
        plan=_plan(),
        expected_ports=EXPECTED_PORTS,
        ref_code=REF_XOR,
        harness_files=HARNESS,
    )


def test_native_plan_round_trip_keeps_sweep_cases_without_p0_modules():
    payload = native_plan_to_dict(_plan())
    assert payload["mode"] == "native_parameter_sweep"
    assert payload["specialization_count"] == 0
    assert payload["sweep_case_count"] == 3
    assert all("module_name" not in row for row in payload["cases"])

    restored = native_plan_from_dict(payload)
    assert restored is not None
    assert restored.parameter_names == ("WIDTH",)
    assert [case.values for case in restored.cases] == [
        {"WIDTH": 3},
        {"WIDTH": 17},
        {"WIDTH": 65},
    ]


def test_parser_and_selector_find_the_parameter_owning_core():
    child = "module child(input logic x, output logic y); assign y=x; endmodule\n"
    modules = parse_native_modules(child + GENERIC_XOR)
    assert [module.name for module in modules] == ["child", "native_xor"]
    assert modules[1].parameter_names == ("WIDTH",)
    assert select_native_core_module(
        child + GENERIC_XOR,
        required_parameters=["WIDTH"],
        preferred_name="native_xor",
    ).name == "native_xor"


def test_generic_core_is_wrapped_with_explicit_parameter_forwarding():
    design, manifest = _prepare()
    assert design is not None, manifest
    assert manifest["contract_pass"] is True
    assert manifest["one_emitted_dut"] is True
    assert manifest["sweep_case_count"] == 3
    assert "module native_xor_sparkle_inner #(\n" in design
    assert "native_xor_sparkle_inner #(\n        .WIDTH(WIDTH)" in design
    assert len({row["sv_sha256"] for row in manifest["cases"]}) == 1
    assert manifest["sv_sha256"] == manifest["cases"][0]["sv_sha256"]


