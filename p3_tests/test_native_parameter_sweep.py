def test_runner_configures_native_metadata_and_prompt_without_p0_aliases():
    harness = {
        "src/test_runner.py": """
            import pytest

            def test_runner(WIDTH=8):
                runner.build(parameters={"WIDTH": WIDTH})
                dut.lhs.value = 0
                dut.rhs.value = 0
                int(dut.out.value)

            @pytest.mark.parametrize("WIDTH", [3, 17, 65])
            def test_sweep(WIDTH):
                test_runner(WIDTH=WIDTH)
        """,
    }
    info = SimpleNamespace(
        design_name="native_xor",
        ref_code=REF_XOR,
        prompt_text="parameter WIDTH; input lhs; input rhs; output out",
        metadata={"dataset": "cvdp", "harness_files": harness},
    )
    configured = ckt_run.configure_parameter_mode(
        info,
        finite_enabled=False,
        native_enabled=True,
    )
    assert "finite_parameter_plan" not in configured.metadata
    payload = configured.metadata["native_parameter_sweep_plan"]
    assert payload["mode"] == "native_parameter_sweep"
    assert [row["parameters"] for row in payload["cases"]] == [
        {"WIDTH": 3}, {"WIDTH": 8}, {"WIDTH": 17}, {"WIDTH": 65},
    ]

    prompt = build_user_message(
        "native_case",
        has_repl=True,
        info=configured,
        dataset_name="cvdp",
    )
    assert "### Native Parameter Sweep (P3)" in prompt
    assert "#synthesizeParameterizedVerilog native_xor [WIDTH := 3]" in prompt
    assert "Do not enumerate sweep values" in prompt
    assert "Repeat the eta-expanded alias" not in prompt


