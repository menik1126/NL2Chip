#!/usr/bin/env bash
# ============================================================
# 实验 3: PPA 优化循环
# 目的: 展示 LLM agent 迭代优化 PPA 的效果
# 选取有代表性的题目 (组合逻辑 + 时序逻辑 + FSM)
# 模型: claude-sonnet-4-5-20250514
# ============================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROJECT_ROOT"

MODEL="claude-sonnet-4-5-20250929"
TIMESTAMP=$(date +%Y%m%d_%H%M%S)

echo "╭──────────────────────────────────────────────╮"
echo "│  实验 3: PPA 优化循环                         │"
echo "│  模型: $MODEL                                 │"
echo "│  PPA 迭代: 5 轮                               │"
echo "╰──────────────────────────────────────────────╯"

# 只跑有 PPA 优化价值的复杂题 (63/156)
# 跳过: 简单门, 直连 wire, 基本 vector, 简单 DFF/计数器, 基本 mux, 单行 assign
PPA_FILTER="Prob(030|035|037|045|054|063|066|067|068|071|074|075|076|078|079|080|082|084|085|086|095|096|097|100|107|108|109|110|111|112|114|115|118|119|120|121|122|123|124|125|127|128|129|133|134|137|138|139|140|141|142|143|144|146|148|149|150|151|152|153|154|155|156)"

LOG="results/exp03_ppa_opt_${TIMESTAMP}.log"
./agent/run_agent.sh \
    -m "$MODEL" \
    -f "$PPA_FILTER" \
    --ppa-opt \
    --ppa-iters 5 \
    --ppa-turns 40 \
    > >(tee "$LOG") 2>&1

echo ""
echo "=== 实验 3 完成 ==="
echo "日志: $LOG"
